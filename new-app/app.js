function startLesson(index) {
  if (!isLessonUnlocked(activeLevel, index)) return;
  quizLesson = index;
  quizIndex = -1;
  quizLocked = false;
  quizAnswerCorrect = null;
  quizScore = 0;
  quizOutcome = null;
  const panel = document.getElementById('quizPanel');
  panel.hidden = false;
  const lesson = lessonsForLevel()[index];
  document.getElementById('quizLabel').textContent = `${text('lessonCheck')} · ${copy[currentLanguage].levelNames[activeLevel]} · ${localized(lesson, 'title').toUpperCase()}`;
  document.getElementById('quizQuestion').textContent = localized(lesson, 'lesson');
  document.getElementById('quizQuestion').dir = currentLanguage === 'fa' ? 'rtl' : 'ltr';
  document.getElementById('quizCount').textContent = text('lesson');
  document.getElementById('quizOptions').replaceChildren();
  document.getElementById('quizFeedback').textContent = '';
  document.getElementById('quizNext').hidden = false;
  document.getElementById('quizNext').textContent = `${text('startQuiz')} →`;
  document.getElementById('quizNext').onclick = renderQuizQuestion;
  panel.scrollIntoView({ behavior: 'smooth', block: 'center' });
}

function renderQuizQuestion() {
  const lesson = lessonsForLevel()[quizLesson];
  quizIndex += 1;
  if (quizIndex >= lesson.questions.length) {
    finishQuiz(lesson);
    return;
  }
  quizLocked = false;
  quizAnswerCorrect = null;
  const question = lesson.questions[quizIndex];
  document.getElementById('quizQuestion').textContent = localized(question, 'prompt');
  document.getElementById('quizQuestion').dir = currentLanguage === 'fa' ? 'rtl' : 'ltr';
  document.getElementById('quizCount').textContent = currentLanguage === 'fa'
    ? `${new Intl.NumberFormat('fa-IR').format(quizIndex + 1)} / ${new Intl.NumberFormat('fa-IR').format(lesson.questions.length)}`
    : currentLanguage === 'es'
      ? `${new Intl.NumberFormat('es-ES').format(quizIndex + 1)} / ${lesson.questions.length}`
      : `${quizIndex + 1} / ${lesson.questions.length}`;
  document.getElementById('quizFeedback').textContent = '';
  document.getElementById('quizNext').hidden = true;
  const options = document.getElementById('quizOptions');
  options.replaceChildren();
  question.options.forEach((option) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.textContent = option;
    button.addEventListener('click', () => {
      if (quizLocked) return;
      quizLocked = true;
      const correct = option === question.answer;
      quizAnswerCorrect = correct;
      if (correct) quizScore += 1;
      options.querySelectorAll('button').forEach((choice) => {
        choice.disabled = true;
        if (choice.textContent === question.answer) choice.classList.add('correct');
      });
      if (!correct) button.classList.add('wrong');
      document.getElementById('quizFeedback').textContent = correct ? text('correctFeedback') : text('wrongFeedback').replace('{answer}', question.answer);
      document.getElementById('quizNext').hidden = false;
      document.getElementById('quizNext').textContent = quizIndex === questionCount(lesson) - 1 ? `${text('finishLesson')} ✓` : `${text('nextQuestion')} →`;
    });
    options.appendChild(button);
  });
  document.getElementById('quizNext').onclick = renderQuizQuestion;
}

function finishQuiz(lesson) {
  quizOutcome = quizScore === lesson.questions.length ? 'passed' : 'retry';
  if (quizOutcome === 'passed') {
    completedLessons.add(lessonKey(activeLevel, quizLesson));
    localStorage.setItem(progressStorageKey(), JSON.stringify([...completedLessons]));
    renderCefrPath();
    renderLessons();
  }
  renderCurrentQuizState();
  document.getElementById('quizOptions').replaceChildren();
  document.getElementById('quizNext').onclick = quizOutcome === 'passed' ? continuePath : () => startLesson(quizLesson);
}

function continuePath() {
  const activeLessons = lessonsForLevel();
  if (quizLesson < activeLessons.length - 1) {
    startLesson(quizLesson + 1);
    return;
  }
  const nextLevel = cefrLevels[cefrLevels.indexOf(activeLevel) + 1];
  if (nextLevel && isLevelUnlocked(nextLevel)) {
    activeLevel = nextLevel;
    renderCefrPath();
    renderLessons();
    startLesson(0);
    return;
  }
  if (cefrLevels.every((level) => lessonsForLevel(level).length > 0 && completedCount(level) === lessonsForLevel(level).length)) {
    document.getElementById('quizQuestion').textContent = text('pathComplete');
    document.getElementById('quizFeedback').textContent = '';
    document.getElementById('quizNext').hidden = true;
    return;
  }
  document.getElementById('quizPanel').hidden = true;
}

function questionCount(lesson) {
  return lesson.questions.length;
}

