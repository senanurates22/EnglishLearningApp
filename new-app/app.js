function progressStorageKey(language = targetLanguage) {
  return `daylight-cefr-completed-${language}`;
}

function loadCompletedLessons(language = targetLanguage) {
  try {
    const saved = JSON.parse(localStorage.getItem(progressStorageKey(language)) || '[]');
    return new Set(Array.isArray(saved) ? saved.filter((item) => typeof item === 'string') : []);
  } catch {
    return new Set();
  }
}

let completedLessons = loadCompletedLessons();

function lessonKey(level, index) {
  return `${level}-${index}`;
}

function lessonsForLevel(level = activeLevel) {
  return level === 'A1' ? createTargetLessons() : [];
}

function localized(item, key) {
  return item[key];
}

function isLessonUnlocked(level, index) {
  if (!isLevelUnlocked(level)) return false;
  return index === 0 || completedLessons.has(lessonKey(level, index - 1));
}

function isLevelUnlocked(level) {
  const levelIndex = cefrLevels.indexOf(level);
  if (levelIndex <= 0) return true;
  if (!lessonsForLevel(level).length) return false;
  const previousLevel = cefrLevels[levelIndex - 1];
  return lessonsForLevel(previousLevel).every((_, index) => completedLessons.has(lessonKey(previousLevel, index)));
}

function completedCount(level) {
  return lessonsForLevel(level).filter((_, index) => completedLessons.has(lessonKey(level, index))).length;
}

