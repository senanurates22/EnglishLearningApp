const recordButton = document.getElementById('recordButton');
const recordStatus = document.getElementById('recordStatus');
const playback = document.getElementById('playback');
if (!window.isSecureContext || !navigator.mediaDevices?.getUserMedia || !window.MediaRecorder) {
  recordButton.disabled = true;
  recordStatus.textContent = text('microphoneUnsupported');
} else {
  recordButton.addEventListener('click', async () => {
    if (mediaRecorder && mediaRecorder.state === 'recording') {
      mediaRecorder.stop();
      recordButton.querySelector('[data-i18n="recordStart"]').textContent = text('recordStart');
      return;
    }
    try {
      mediaStream = await navigator.mediaDevices.getUserMedia({ audio: true });
      const mimeType = ['audio/webm;codecs=opus', 'audio/mp4'].find((type) => MediaRecorder.isTypeSupported?.(type));
      mediaRecorder = mimeType ? new MediaRecorder(mediaStream, { mimeType }) : new MediaRecorder(mediaStream);
      const chunks = [];
      mediaRecorder.ondataavailable = (event) => { if (event.data.size) chunks.push(event.data); };
      mediaRecorder.onerror = () => {
        mediaStream?.getTracks().forEach((track) => track.stop());
        recordStatus.textContent = text('microphoneFailed');
        recordButton.querySelector('[data-i18n="recordStart"]').textContent = text('recordAgain');
      };
      mediaRecorder.onstop = () => {
        mediaStream?.getTracks().forEach((track) => track.stop());
        if (!chunks.length) {
          recordStatus.textContent = text('microphoneEmpty');
          return;
        }
        if (recordingUrl) URL.revokeObjectURL(recordingUrl);
        recordingUrl = URL.createObjectURL(new Blob(chunks, { type: mediaRecorder.mimeType || undefined }));
        playback.src = recordingUrl;
        playback.hidden = false;
        recordStatus.textContent = text('microphoneReady');
      };
      mediaRecorder.start();
      recordButton.querySelector('[data-i18n="recordStart"]').textContent = text('stopRecording');
      recordStatus.textContent = text('microphoneRecording');
    } catch (error) {
      mediaStream?.getTracks().forEach((track) => track.stop());
      if (error.name === 'NotAllowedError' || error.name === 'SecurityError') {
        recordStatus.textContent = text('microphoneDenied');
      } else if (error.name === 'NotFoundError') {
        recordStatus.textContent = text('microphoneMissing');
      } else {
        recordStatus.textContent = text('microphoneError');
      }
    }
  });
}

