function targetPhrase(item, example = false) {
  if (targetLanguage === 'es') return example ? item.exampleMeaningEs : item.meaningEs;
  return example ? item.exampleMeaning : item.meaning;
}

function createTargetLessons() {
  return courseUnits.map((unit) => ({
    level: 'A1',
    title: unit.title,
    detail: unit.detail,
    lesson: unit.lesson,
    questions: unit.wordIndexes.map((wordIndex) => {
      const item = words[wordIndex];
      const options = [item.word, words[(wordIndex + 2) % words.length].word, words[(wordIndex + 4) % words.length].word];
      return {
        prompt: `What does “${targetPhrase(item)}” mean in English?`,
        options,
        answer: item.word
      };
    })
  }));
}

